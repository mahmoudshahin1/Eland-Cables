/**
 * Adapt any raw MasterCableCatalogItem from PostgreSQL into a safe VipCableItem
 */
export function adaptMasterCableToVipCable(raw: any): VipCableItem {
  const code = String(raw.cableCode || raw.code || raw.id || '10009530');
  const desc = String(raw.description || raw.name || 'Standard Copper Cable');
  const voltageClass = raw.voltageClass === 'MV' ? 'MV' : 'LV';
  
  let std = 'BS 5467';
  if (desc.includes('BS 6724') || desc.includes('LSOH')) std = 'BS 6724';
  else if (desc.includes('IEC 60502-2') || desc.includes('6/10') || desc.includes('11kV')) std = 'IEC 60502-2';
  else if (desc.includes('IEC 60502-1') || desc.includes('N2XH')) std = 'IEC 60502-1';
  else if (desc.includes('BS 5467') || desc.includes('SWA')) std = 'BS 5467';

  let cores = 4;
  if (raw.cores === '1C' || desc.includes('1X') || desc.includes('1x') || desc.includes('Single')) cores = 1;
  else if (raw.cores === '3C' || desc.includes('3X') || desc.includes('3x')) cores = 3;
  else if (raw.cores === '4C' || desc.includes('4X') || desc.includes('4x')) cores = 4;

  const size = raw.crossSectionMm2 ? `${raw.crossSectionMm2} mm²` : '70 mm²';
  const od = Number(raw.outerDiameterMm) || 34.8;
  const weightKgKm = Number(raw.approxWeightKgKm) || 3450;
  const copperWeightKgKm = Math.round(weightKgKm * 0.72);

  return {
    code,
    name: desc,
    std,
    voltage: voltageClass === 'MV' ? '6/10 kV' : '0.6/1 kV',
    cores,
    size,
    od,
    weightKgKm,
    copperWeightKgKm,
    category: voltageClass,
    description: desc,
  };
}
